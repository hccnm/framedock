import { _electron } from '/Users/ethanhuang/Desktop/codespace/test/dsh-codex-memory/node_modules/playwright-core/index.mjs';
import fs from 'node:fs/promises';
import path from 'node:path';
const root = path.resolve('verification/naked-sheep-e2e');
const application = await _electron.launch({ executablePath: path.resolve('desktop/node_modules/electron/dist/Electron.app/Contents/MacOS/Electron'), args: [path.resolve('desktop')] });
const page = await application.firstWindow();
await page.waitForURL('app://framedock/**');
await page.waitForFunction(() => !!window.canvasDesktop?.storage);
const result = await page.evaluate(async () => {
  const bridge = window.canvasDesktop;
  if (!bridge?.storage) throw new Error('Missing actual desktop storage bridge');
  const connection = await bridge.getAgentConnection();
  if (!connection) throw new Error('Missing embedded agent connection');
  const response = await fetch(`${connection.url.replace(/\/$/, '')}/agent/codex/workspace`, { headers: { 'x-canvas-agent-token': connection.token } });
  if (!response.ok) throw new Error(`Workspace HTTP ${response.status}`);
  const data = await response.json();
  const canvas = JSON.parse(await bridge.storage.getState('framedock:canvas_store'));
  return { workspacePath: data.workspace.workspacePath, folders: canvas.state.projectFolders.map(x => ({ id: x.id, name: x.name })), pages: canvas.state.projects.map(x => ({ id: x.id, title: x.title, nodes: x.nodes.length })) };
});
await page.goto('app://framedock/projects');
await page.getByRole('heading', { name: '裸羊逃跑事件', exact: true }).waitFor();
await page.screenshot({ path: path.join(root, 'desktop-project-library.png') });
const e2e = result.pages.find(x => x.title === 'E2E生成验收');
await page.goto(`app://framedock/canvas/${e2e.id}`);
await page.waitForSelector('[data-node-id]');
result.imageDiagnostics = await page.evaluate(() => ({ text: document.body.innerText.slice(-2000), images: [...document.querySelectorAll('img')].map(x => ({ src: x.src.slice(0,100), complete: x.complete, width: x.naturalWidth })) }));
result.generatedImageRestored = await page.locator('[data-node-id] img').first().evaluate(x => x.complete && x.naturalWidth > 0).catch(() => false);
await page.screenshot({ path: path.join(root, 'desktop-e2e-canvas.png') });
await page.goto('app://framedock/skills');
await page.getByRole('heading', { name: '技能', exact: true }).waitFor();
result.skills = await page.evaluate(async () => {
  const connection = await window.canvasDesktop.getAgentConnection();
  const response = await fetch(`${connection.url.replace(/\/$/, '')}/agent/api/skills`, { headers: { 'x-canvas-agent-token': connection.token } });
  return { status: response.status, ...(await response.json()) };
});
await page.waitForFunction(() => document.body.innerText.includes('韩剧') || document.body.innerText.includes('korean-thriller') || document.body.innerText.includes('storylens')).catch(() => {});
result.skillPageText = await page.locator('body').innerText();
result.skillVisible = result.skillPageText.includes('韩剧') || result.skillPageText.includes('korean-thriller') || result.skillPageText.includes('storylens');
await page.screenshot({ path: path.join(root, 'desktop-fisher-skill.png') });
await fs.writeFile(path.join(root, 'desktop-check.json'), JSON.stringify(result, null, 2));
console.log(JSON.stringify({ workspacePath: result.workspacePath, folders: result.folders, pageCount: result.pages.length, generatedImageRestored: result.generatedImageRestored, skillVisible: result.skillVisible, skillErrors: result.skills.errors }));
await application.close();
